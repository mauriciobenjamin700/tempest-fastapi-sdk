def _write_models(root: Path, columns: str) -> None:
    """Write the model module with ``columns`` appended to ``ThingModel``.

    Args:
        root (Path): The project root.
        columns (str): Column declarations, indented for the class body.
    """
    (root / "envmodels" / "__init__.py").write_text(HEADER + columns, encoding="utf-8")


@pytest.fixture
def project(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Scaffold an Alembic project whose metadata comes from ``envmodels``.

    Args:
        tmp_path (Path): Pytest's per-test directory.
        monkeypatch (pytest.MonkeyPatch): Moves the working directory.

    Returns:
        Path: The project root.
    """
    (tmp_path / "envmodels").mkdir()
    _write_models(tmp_path, "")
    monkeypatch.chdir(tmp_path)
    AlembicHelper(config_path=str(tmp_path / "alembic.ini")).init(
        directory="alembic",
        metadata_module="envmodels",
    )
    return tmp_path


def _revision(root: Path, url: str, message: str) -> str:
    """Autogenerate a revision and return its source.

    Args:
        root (Path): The project root.
        url (str): The database URL.
        message (str): The revision message, unique per project.

    Returns:
        str: The source of the revision file just written.
    """
    _ok(_alembic(root, url, "revision", "--autogenerate", "-m", message))
    (revision,) = (root / "alembic" / "versions").glob(f"*{message}*.py")
    return revision.read_text(encoding="utf-8")


def _sqlite_checks(root: Path) -> list[str]:
    """List the ``CONSTRAINT <name> CHECK`` names of the ``things`` table.

    Args:
        root (Path): The project root holding ``app.db``.

    Returns:
        list[str]: The check names, in DDL order.
    """
    connection = sqlite3.connect(root / "app.db")
    try:
        (sql,) = connection.execute(
            "SELECT sql FROM sqlite_master WHERE name = 'things'"
        ).fetchone()
    finally:
        connection.close()
    parts = sql.split("CONSTRAINT ")[1:]
    return [part.split()[0] for part in parts if " CHECK " in f" {part}"]


@pytest.fixture(scope="module")
def postgres_server() -> Iterator[str]:
    """Yield an asyncpg URL to a PostgreSQL server.

    ``TEST_POSTGRES_URL`` wins; otherwise a container is started.

    Yields:
        str: An asyncpg URL whose user may create databases.
    """
    configured = os.environ.get("TEST_POSTGRES_URL")
    if configured:
        yield configured
        return
    if shutil.which("docker") is None:
        pytest.skip("docker CLI not installed")
    if subprocess.run(["docker", "info"], capture_output=True).returncode != 0:
        pytest.skip("docker daemon not reachable")
    subprocess.run(["docker", "rm", "-f", POSTGRES_CONTAINER], capture_output=True)
    started = subprocess.run(
        [
            "docker",
            "run",
            "-d",
            "--name",
            POSTGRES_CONTAINER,
            "-e",
            "POSTGRES_PASSWORD=probe",
            "-e",
            "POSTGRES_DB=probe",
            "-p",
            f"{POSTGRES_PORT}:5432",
            POSTGRES_IMAGE,
        ],
        capture_output=True,
        text=True,
    )
    if started.returncode != 0:
        pytest.skip(f"could not start {POSTGRES_IMAGE}: {started.stderr.strip()}")
    try:
        deadline = time.monotonic() + 60
        while time.monotonic() < deadline:
            ready = subprocess.run(
                [
                    "docker",
                    "exec",
                    POSTGRES_CONTAINER,
                    "pg_isready",
                    "-U",
                    "postgres",
                    "-h",
                    "127.0.0.1",
                ],
                capture_output=True,
            )
            if ready.returncode == 0:
                break
            time.sleep(0.5)
        yield f"postgresql+asyncpg://postgres:probe@127.0.0.1:{POSTGRES_PORT}/probe"
    finally:
        subprocess.run(["docker", "rm", "-f", POSTGRES_CONTAINER], capture_output=True)


async def _execute(url: str, *statements: str) -> list[list[tuple[object, ...]]]:
    """Run statements on PostgreSQL in autocommit mode.

    Args:
        url (str): The asyncpg URL.
        *statements (str): SQL statements, run in order.

    Returns:
        list[list[tuple[object, ...]]]: The rows of each statement; empty
        for a statement that returns none.
    """
    engine = create_async_engine(url, isolation_level="AUTOCOMMIT")
    try:
        results: list[list[tuple[object, ...]]] = []
        async with engine.connect() as connection:
            for statement in statements:
                result = await connection.exec_driver_sql(statement)
                results.append(
                    [tuple(row) for row in result] if result.returns_rows else []
                )
        return results
    finally:
        await engine.dispose()


@pytest.fixture
def postgres_url(postgres_server: str) -> Iterator[str]:
    """Yield a URL to a fresh, empty PostgreSQL database for one test.

    Args:
        postgres_server (str): The server URL.

    Yields:
        str: An asyncpg URL to a database no other test touches.
    """
    name = f"lifecycle_{uuid.uuid4().hex[:12]}"
    asyncio.run(_execute(postgres_server, f"CREATE DATABASE {name}"))
    base = postgres_server.rsplit("/", 1)[0]
    try:
        yield f"{base}/{name}"
    finally:
        asyncio.run(_execute(postgres_server, f"DROP DATABASE IF EXISTS {name}"))


def _enum_types(url: str) -> list[str]:
    """List the enum types of a PostgreSQL database, sorted.

    Args:
        url (str): The asyncpg URL.

    Returns:
        list[str]: Every ``typname`` with ``typtype = 'e'``.
    """
    (rows,) = asyncio.run(
        _execute(url, "SELECT typname FROM pg_type WHERE typtype = 'e'"),
    )
    return sorted(str(row[0]) for row in rows)


class TestEnumTypeName:
    """#518: the class suffix and the type suffix do not stack."""

    def test_class_ending_in_enum_is_not_doubled(self) -> None:
        class CandidateSlugEnum(enum.StrEnum):
            ALPHA = "alpha"

        assert enum_type_name(CandidateSlugEnum) == "candidate_slug_enum"

    def test_class_without_the_suffix_is_unchanged(self) -> None:
        class OrderStatus(enum.StrEnum):
            OPEN = "open"

        assert enum_type_name(OrderStatus) == "order_status_enum"

    def test_both_spellings_share_one_type(self) -> None:
        class AreaScope(enum.StrEnum):
            CITY = "city"

        class AreaScopeEnum(enum.StrEnum):
            CITY = "city"

        assert enum_type_name(AreaScope) == enum_type_name(AreaScopeEnum)

    def test_only_one_trailing_suffix_is_dropped(self) -> None:
        class StatusEnumEnum(enum.StrEnum):
            ON = "on"

        assert enum_type_name(StatusEnumEnum) == "status_enum_enum"

    def test_a_class_called_enum_keeps_its_name(self) -> None:
        bare = enum.Enum("Enum", ["ON"])
        assert enum_type_name(bare) == "enum_enum"


class TestRenameEnumTypeOp:
    """The operation itself: DDL, reversal and rendering."""

    @staticmethod
    def _offline_sql(dialect: str, operation: RenameEnumTypeOp) -> str:
        """Run the operation in offline mode and return the emitted SQL.

        Args:
            dialect (str): The dialect name.
            operation (RenameEnumTypeOp): The operation to run.

        Returns:
            str: Everything written to the offline buffer.
        """
        buffer = StringIO()
        context = MigrationContext.configure(
            dialect_name=dialect,
            opts={"as_sql": True, "output_buffer": buffer},
        )
        Operations(context).invoke(operation)
        return buffer.getvalue()

    def test_postgresql_renames_the_type(self) -> None:
        sql = self._offline_sql(
            "postgresql", RenameEnumTypeOp("slug_enum_enum", "slug_enum")
        )
        assert "ALTER TYPE slug_enum_enum RENAME TO slug_enum" in sql

    def test_schema_and_quoting_are_applied(self) -> None:
        sql = self._offline_sql(
            "postgresql",
            RenameEnumTypeOp("Old Slug", "slug_enum", schema="tenant"),
        )
        assert 'ALTER TYPE tenant."Old Slug" RENAME TO slug_enum' in sql

    def test_sqlite_offline_refuses(self) -> None:
        operation = RenameEnumTypeOp(
            "a_enum", "b_enum", columns=[EnumColumnRef(table="t", column="c")]
        )
        with pytest.raises(NotImplementedError, match="live connection"):
            self._offline_sql("sqlite", operation)

    def test_reverse_swaps_the_names(self) -> None:
        ref = EnumColumnRef(table="things", column="slug")
        reverse = RenameEnumTypeOp("a_enum", "b_enum", columns=[ref]).reverse()
        assert (reverse.old_name, reverse.new_name) == ("b_enum", "a_enum")
        assert reverse.columns == (ref,)

    def test_render_reproduces_the_call(self) -> None:
        operation = RenameEnumTypeOp(
            "a_enum", "b_enum", columns=[EnumColumnRef(table="t", column="c")]
        )
        code = render_python_code(
            UpgradeOps(ops=[operation]), render_item=render_enum_types
        )
        assert (
            "op.rename_enum_type('a_enum', 'b_enum', "
            "columns=[EnumColumnRef(table='t', column='c')])"
        ) in code

    def test_sqlite_renames_only_the_named_columns_check(self) -> None:
        engine = sa.create_engine("sqlite://")
        with engine.begin() as connection:
            connection.exec_driver_sql(
                "CREATE TABLE things (id INTEGER PRIMARY KEY, "
                "slug VARCHAR(5), other VARCHAR(5), "
                "CONSTRAINT ck_things_slug_enum_enum CHECK (slug IN ('a', 'b')), "
                "CONSTRAINT ck_things_other_enum CHECK (other IN ('a', 'b')))"
            )
            connection.exec_driver_sql("INSERT INTO things VALUES (1, 'a', 'b')")
            operations = Operations(MigrationContext.configure(connection))
            operations.rename_enum_type(  # type: ignore[attr-defined]
                "slug_enum_enum",
                "slug_enum",
                columns=[EnumColumnRef(table="things", column="slug")],
            )
            checks = {
                check["name"]: check["sqltext"]
                for check in sa.inspect(connection).get_check_constraints("things")
            }
            rows = connection.exec_driver_sql("SELECT * FROM things").fetchall()
        assert set(checks) == {"ck_things_slug_enum", "ck_things_other_enum"}
        assert rows == [(1, "a", "b")]


class TestRenameIsAutogenerated:
    """A database holding the doubled name gets ``op.rename_enum_type``."""

    def test_sqlite(self, project: Path) -> None:
        url = f"sqlite+aiosqlite:///{project / 'app.db'}"
        _write_models(project, LEGACY_SLUG)
        _revision(project, url, "legacy")
        _ok(_alembic(project, url, "upgrade", "head"))
        assert _sqlite_checks(project) == ["ck_things_candidate_slug_enum_enum"]

        _write_models(project, CURRENT_SLUG)
        source = _revision(project, url, "rename")
        assert "op.rename_enum_type(" in source
        assert '"candidate_slug_enum_enum"' in source
        assert "replace_enum" not in source
        assert "drop_constraint" not in source

        _ok(_alembic(project, url, "upgrade", "head"))
        assert _sqlite_checks(project) == ["ck_things_candidate_slug_enum"]
        _ok(_alembic(project, url, "check"))
        _ok(_alembic(project, url, "downgrade", "-1"))
        assert _sqlite_checks(project) == ["ck_things_candidate_slug_enum_enum"]

    def test_nothing_is_emitted_when_the_name_did_not_change(
        self, project: Path
    ) -> None:
        url = f"sqlite+aiosqlite:///{project / 'app.db'}"
        _write_models(project, CURRENT_SLUG)
        _revision(project, url, "init")
        _ok(_alembic(project, url, "upgrade", "head"))
        _ok(_alembic(project, url, "check"))

    @pytest.mark.docker
    def test_postgresql(self, project: Path, postgres_url: str) -> None:
        """The rename keeps the rows, and the model can write again."""
        _write_models(project, LEGACY_SLUG)
        _revision(project, postgres_url, "legacy")
        _ok(_alembic(project, postgres_url, "upgrade", "head"))
        asyncio.run(
            _execute(
                postgres_url,
                "INSERT INTO things (id, is_active, created_at, updated_at, "
                "name, slug) VALUES (gen_random_uuid(), true, now(), now(), "
                "'n', 'alpha')",
            )
        )
        assert _enum_types(postgres_url) == ["candidate_slug_enum_enum"]

        _write_models(project, CURRENT_SLUG)
        source = _revision(project, postgres_url, "rename")
        assert "op.rename_enum_type(" in source

        _ok(_alembic(project, postgres_url, "upgrade", "head"))
        assert _enum_types(postgres_url) == ["candidate_slug_enum"]
        (rows,) = asyncio.run(_execute(postgres_url, "SELECT slug FROM things"))
        assert rows == [("alpha",)]
        _ok(_alembic(project, postgres_url, "check"))
        _ok(_alembic(project, postgres_url, "downgrade", "-1"))
        assert _enum_types(postgres_url) == ["candidate_slug_enum_enum"]


ADDED_COLUMNS: dict[str, str] = {
    "one_enum": "    age_range: Mapped[AgeRange | None]\n",
    "two_enums": (
        "    age_range: Mapped[AgeRange | None]\n"
        "    age_source: Mapped[Source | None]\n"
    ),
    "one_enum_twice": (
        "    age_range: Mapped[AgeRange | None]\n"
        "    store_age_range: Mapped[AgeRange | None]\n"
    ),
}
"""The issue's three cases: A, B and C."""


def _columns(case: str) -> list[str]:
    """List the enum columns a case adds.

    Args:
        case (str): A key of :data:`ADDED_COLUMNS`.

    Returns:
        list[str]: The column names.
    """
    return [line.split(":")[0].strip() for line in ADDED_COLUMNS[case].splitlines()]


def _sqlite_rejects(root: Path, column: str) -> bool:
    """Whether SQLite refuses a value outside the enum in ``column``.

    Args:
        root (Path): The project root holding ``app.db``.
        column (str): The enum column to write.

    Returns:
        bool: ``True`` when the insert fails on a ``CHECK``.
    """
    connection = sqlite3.connect(root / "app.db")
    try:
        connection.execute(
            "INSERT INTO things (id, is_active, created_at, updated_at, name, "
            f"{column}) VALUES ('x', 1, '2026-01-01', '2026-01-01', 'n', 'LIXO')"
        )
    except sqlite3.IntegrityError as exc:
        return "CHECK constraint failed" in str(exc)
    finally:
        connection.rollback()
        connection.close()
    return False


class TestEnumColumnsAddedInBatch:
    """#526 on SQLite: up, down and up again, with every column enforced."""

    @pytest.mark.parametrize("case", sorted(ADDED_COLUMNS))
    def test_round_trip(self, project: Path, case: str) -> None:
        url = f"sqlite+aiosqlite:///{project / 'app.db'}"
        _revision(project, url, "init")
        _ok(_alembic(project, url, "upgrade", "head"))

        _write_models(project, ADDED_COLUMNS[case])
        source = _revision(project, url, "add")
        assert "batch_op.create_enum_check(" in source
        assert "batch_op.drop_enum_check(" in source
        assert "create_constraint=True" not in source

        _ok(_alembic(project, url, "upgrade", "head"))
        columns = _columns(case)
        assert all(_sqlite_rejects(project, column) for column in columns)
        assert len(_sqlite_checks(project)) == len(columns)
        _ok(_alembic(project, url, "check"))

        _ok(_alembic(project, url, "downgrade", "-1"))
        assert _sqlite_checks(project) == []
        _ok(_alembic(project, url, "upgrade", "head"))
        assert all(_sqlite_rejects(project, column) for column in columns)

    def test_shared_enum_in_a_new_table_survives_a_later_batch(
        self, project: Path
    ) -> None:
        """Both checks get their own name, so the next rebuild keeps both."""
        url = f"sqlite+aiosqlite:///{project / 'app.db'}"
        _write_models(project, ADDED_COLUMNS["one_enum_twice"])
        source = _revision(project, url, "init")
        assert "op.create_enum_check(" in source
        _ok(_alembic(project, url, "upgrade", "head"))
        assert _sqlite_checks(project) == [
            "ck_things_age_range_enum",
            "ck_things_age_range_enum_store_age_range",
        ]

        _write_models(
            project, ADDED_COLUMNS["one_enum_twice"] + "    note: Mapped[str | None]\n"
        )
        _revision(project, url, "note")
        _ok(_alembic(project, url, "upgrade", "head"))
        assert _sqlite_rejects(project, "age_range")
        assert _sqlite_rejects(project, "store_age_range")
        _ok(_alembic(project, url, "check"))
