"""Enum types through a project's migration history, end to end.

Every case scaffolds a project with :meth:`AlembicHelper.init`, writes a
first model module, generates and applies a revision, then edits the
models and lets ``alembic revision --autogenerate`` write the next one —
the way a service evolves. The bare ``alembic`` CLI runs in a subprocess,
against SQLite always and against PostgreSQL when a container is
available (marked ``docker``: ``make test-docker`` or
``TEST_POSTGRES_URL``).

* #518: :func:`enum_type_name` no longer doubles the suffix of a class
  ending in ``Enum``, and a database that still holds the doubled name
  gets an autogenerated ``op.rename_enum_type``.
* #526: enum columns added through ``batch_alter_table`` keep one
  ``CHECK`` each on SQLite (two columns of one enum used to share a name,
  and the batch kept one), and the downgrade that drops them runs.
"""

