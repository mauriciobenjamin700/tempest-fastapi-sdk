"""Brazilian municipalities: lookup by code or name, and found in free text.

Every one of the 5571 IBGE municipalities (the 5570 plus Brasília, the
Federal District) ships offline with its IBGE code, official name, state,
coordinate and capital flag (:mod:`._br_municipalities_data`, generated by
``scripts/regen_br_municipalities.py``). On top of it:

* :func:`br_municipalities` / :func:`municipality_by_ibge_code` — the list
  and the code lookup.
* :func:`search_municipalities` — "which municipality is this name?", typos
  included, optionally within one state.
* :func:`find_municipalities_in_text` — "which city is the user talking
  about?" in a sentence such as ``"moro em sao jose dos campos - sp"``.

Matching is lexical (:mod:`tempest_fastapi_sdk.text`): no model, no network,
and the index is built once per process on first use.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass
from functools import lru_cache

from tempest_fastapi_sdk.geo.schemas import Coordinate
from tempest_fastapi_sdk.text import FuzzyIndex, Token, normalize_text, tokenize
from tempest_fastapi_sdk.utils.locations import UFEnum, list_states

BRASILIA_IBGE_CODE: int = 5300108
"""IBGE code of Brasília, the single municipality of the Federal District."""

BR_CITY_NICKNAMES: dict[str, int] = {
    "bh": 3106200,
    "beagá": 3106200,
    "sampa": 3550308,
    "floripa": 4205407,
    "poa": 4314902,
    "bsb": 5300108,
    "jampa": 2507507,
    "sjc": 3549904,
    "rio": 3304557,
}
"""Common nicknames and abbreviations, normalized on lookup, to IBGE codes.

Belo Horizonte, São Paulo, Florianópolis, Porto Alegre, Brasília, João
Pessoa, São José dos Campos and Rio de Janeiro. A short list on purpose:
every entry is a word most Brazilians read as that city. In a text it is a
one-word name like any other, so it needs a sign of being a place — a
locative cue before it (``"vou pra bh"``), an uppercase first letter
(``"Rio"``), a state after it, or being the whole text (``"bh"``) — and
``"o bh do time"`` scores below the default ``min_score``.
"""

LOCATIVE_CUES: frozenset[str] = frozenset(
    {
        "em",
        "de",
        "da",
        "do",
        "para",
        "pra",
        "pro",
        "ate",
        "moro",
        "morando",
        "vivo",
        "cidade",
        "municipio",
        "natural",
        "nasci",
        "perto",
        "proximo",
        "regiao",
    }
)
"""Normalized words that, right before a name, make it read as a place."""

FUZZY_EDGE_STOPWORDS: frozenset[str] = frozenset(
    {
        "a",
        "o",
        "as",
        "os",
        "e",
        "ao",
        "aos",
        "um",
        "uma",
        "que",
        "com",
        "na",
        "no",
        "nas",
        "nos",
        "se",
        "eu",
        "ele",
        "ela",
        "mas",
        "por",
        "sem",
        "muito",
        "mais",
        "esta",
        "estou",
        "foi",
        "vai",
        "vou",
        "tem",
    }
)
"""Words a typo-tolerant window may not start or end with.

A run like ``"está ao"`` is two edits from ``"Estação"``, and a long text
holds thousands of such runs. The exact lookup still sees every window, so a
municipality whose name starts or ends with one of these words is still
found when written correctly; only the typo search skips them, which also
spares it most of the windows of a long text.
"""

UNCUED_SINGLE_WORD_FACTOR: float = 0.5
"""Score factor for a one-word match with no sign of being a place.

``"Feliz"``, ``"Natal"`` and ``"Alegre"`` are municipalities and everyday
words. A lowercase single word with no locative cue before it
(:data:`LOCATIVE_CUES`), no state after it, and other words around it is
kept at half the score, so ``"estou feliz"`` ranks below the default
``min_score`` while ``"moro em feliz"``, ``"Feliz/RS"`` and a text that is
only ``"feliz"`` (a form's city field) do not.
"""

MAX_NAME_TOKENS: int = 7
"""Longest municipality name, in words (``São José do Vale do Rio Preto``)."""

STATE_SEPARATORS: frozenset[str] = frozenset(
    {"", "-", "/", ",", "\u2013", "\u2014", "(", ")"}
)
"""What may sit between a name and the state that follows it (spaces stripped)."""


@dataclass(frozen=True, slots=True)
class Municipality:
    """A Brazilian municipality.

    Attributes:
        ibge_code (int): The seven-digit IBGE code.
        name (str): The official IBGE name.
        uf (UFEnum): Its state.
        coordinate (Coordinate): The town centre.
        capital (bool): Whether it is the state capital.
        aliases (tuple[str, ...]): Other spellings in use (``"Açu"`` for
            ``"Assú"``).
    """

    ibge_code: int
    name: str
    uf: UFEnum
    coordinate: Coordinate
    capital: bool
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class MunicipalityMatch:
    """A municipality found for a name or in a text.

    Attributes:
        municipality (Municipality): The match.
        score (float): ``1.0`` for an exact name with its state confirmed,
            lower for typos, a missing state or a one-word match with no
            sign of being a place.
        matched_text (str): The text that matched, as written.
        start (int): Offset of ``matched_text`` in the input.
        end (int): Offset just past it.
        uf_confirmed (bool): Whether the input named the municipality's
            state next to it.
    """

    municipality: Municipality
    score: float
    matched_text: str
    start: int
    end: int
    uf_confirmed: bool


@lru_cache(maxsize=1)
def br_municipalities() -> tuple[Municipality, ...]:
    """Return every Brazilian municipality, ordered by IBGE code.

    Parsed from the bundled data on first call and cached.

    Returns:
        tuple[Municipality, ...]: The 5571 municipalities.
    """
    from tempest_fastapi_sdk.geo._br_municipalities_data import (
        BR_MUNICIPALITIES_CSV,
    )

    found: list[Municipality] = []
    for code, name, uf, latitude, longitude, capital, aliases in csv.reader(
        io.StringIO(BR_MUNICIPALITIES_CSV)
    ):
        found.append(
            Municipality(
                ibge_code=int(code),
                name=name,
                uf=UFEnum(uf),
                coordinate=Coordinate(
                    latitude=float(latitude), longitude=float(longitude)
                ),
                capital=capital == "1",
                aliases=tuple(alias for alias in aliases.split("|") if alias),
            )
        )
    return tuple(found)


@lru_cache(maxsize=1)
def _by_code() -> dict[int, Municipality]:
    """Index the municipalities by IBGE code.

    Returns:
        dict[int, Municipality]: Code to municipality.
    """
    return {
        municipality.ibge_code: municipality for municipality in br_municipalities()
    }


def municipality_by_ibge_code(code: int) -> Municipality | None:
    """Return the municipality with this IBGE code.

    Args:
        code (int): The seven-digit IBGE code.

    Returns:
        Municipality | None: The municipality, or ``None`` for an unknown code.
    """
    return _by_code().get(code)


@lru_cache(maxsize=1)
def _name_index() -> FuzzyIndex[Municipality]:
    """Index official names, aliases, nicknames and the DF regions.

    The Federal District's administrative regions (Ceilândia, Gama, ...),
    listed in :func:`~tempest_fastapi_sdk.utils.locations.list_states`, point
    at Brasília: someone who lives there says the region, not the city.

    Returns:
        FuzzyIndex[Municipality]: Name to municipality.
    """
    index: FuzzyIndex[Municipality] = FuzzyIndex()
    for municipality in br_municipalities():
        index.add(municipality.name, municipality)
        for alias in municipality.aliases:
            index.add(alias, municipality)
    by_code = _by_code()
    for nickname, code in BR_CITY_NICKNAMES.items():
        index.add(nickname, by_code[code])
    brasilia = by_code[BRASILIA_IBGE_CODE]
    known = {normalize_text(brasilia.name)}
    for state in list_states():
        if state.uf is UFEnum.DF:
            for region in state.cities:
                if normalize_text(region) not in known:
                    index.add(region, brasilia)
    return index


@lru_cache(maxsize=1)
def _state_names() -> dict[str, UFEnum]:
    """Map every normalized state name and acronym to its UF.

    Returns:
        dict[str, UFEnum]: ``"sao paulo"`` and ``"sp"`` to ``UFEnum.SP``.
    """
    names: dict[str, UFEnum] = {}
    for state in list_states():
        names[normalize_text(state.name)] = state.uf
        names[state.uf.value.lower()] = state.uf
    return names


def search_municipalities(
    name: str,
    *,
    uf: UFEnum | str | None = None,
    limit: int | None = 5,
    cutoff: float = 0.8,
) -> list[MunicipalityMatch]:
    """Find the municipalities whose name looks like ``name``.

    Args:
        name (str): A municipality name as typed: any case, accents or not,
            typos included (``"sao paolo"``). Aliases, nicknames
            (:data:`BR_CITY_NICKNAMES`) and the Federal District's regions
            are names too.
        uf (UFEnum | str | None): Keep only this state.
        limit (int | None): Most matches to return; ``None`` for all.
        cutoff (float): Lowest name similarity accepted, in ``(0, 1]``.

    Returns:
        list[MunicipalityMatch]: Best first. Homonyms tie: ``"Bom Jesus"``
        without ``uf`` returns every Bom Jesus with the same score.
        ``uf_confirmed`` is ``True`` when ``uf`` was given.
    """
    state = UFEnum(str(uf).upper()) if uf is not None else None
    matches: list[MunicipalityMatch] = []
    seen: set[int] = set()
    for hit in _name_index().search(name, limit=None, cutoff=cutoff):
        municipality = hit.value
        if state is not None and municipality.uf is not state:
            continue
        if municipality.ibge_code in seen:
            continue
        seen.add(municipality.ibge_code)
        matches.append(
            MunicipalityMatch(
                municipality=municipality,
                score=hit.score,
                matched_text=name,
                start=0,
                end=len(name),
                uf_confirmed=state is not None,
            )
        )
    return matches if limit is None else matches[:limit]


def _state_after(text: str, tokens: list[Token], end: int) -> tuple[UFEnum, int] | None:
    """Read a state written right after a name (``"Campinas/SP"``).

    Args:
        text (str): The original text.
        tokens (list[Token]): Its tokens.
        end (int): Index of the first token after the name.

    Returns:
        tuple[UFEnum, int] | None: The state and the index just past it, or
        ``None`` when the next words are not a state (or are separated from
        the name by more than punctuation).
    """
    if end >= len(tokens) or end == 0:
        return None
    gap = text[tokens[end - 1].end : tokens[end].start].replace(" ", "")
    if gap not in STATE_SEPARATORS:
        return None
    names = _state_names()
    for length in (3, 2, 1):
        if end + length > len(tokens):
            continue
        phrase = " ".join(token.text for token in tokens[end : end + length])
        state = names.get(phrase)
        if state is None:
            continue
        if length == 1 and len(phrase) == 2:
            written = tokens[end].original
            if not written.isupper() and gap == "":
                continue
        return state, end + length
    return None


def _looks_like_place(text: str, tokens: list[Token], start: int, end: int) -> bool:
    """Tell a one-word name used as a place from the same word in prose.

    Args:
        text (str): The original text.
        tokens (list[Token]): Its tokens.
        start (int): Index of the name's first token.
        end (int): Index just past its last token.

    Returns:
        bool: ``True`` when the name has more than one word, is the whole
        text (a form field holding ``"campinas"``, optionally with its
        state after it), starts with an uppercase letter, follows a
        locative cue, or is followed by a state.
    """
    if end - start > 1:
        return True
    if start == 0:
        state = _state_after(text, tokens, end)
        if end == len(tokens) or (state is not None and state[1] == len(tokens)):
            return True
    if tokens[start].original[:1].isupper():
        return True
    if start > 0 and tokens[start - 1].text in LOCATIVE_CUES:
        return True
    return _state_after(text, tokens, end) is not None


def find_municipalities_in_text(
    text: str,
    *,
    limit: int | None = 5,
    cutoff: float = 0.85,
    min_score: float = 0.6,
) -> list[MunicipalityMatch]:
    """Find the municipalities a free-form text mentions.

    Every run of up to :data:`MAX_NAME_TOKENS` words is looked up, exactly
    first and then with typos (``cutoff``). A state written right after the
    name (``"Campinas/SP"``, ``"Campinas - São Paulo"``, ``"campinas SP"``)
    keeps only the homonyms in that state and marks them ``uf_confirmed``;
    a state written there that the name does not exist in drops the match.
    Overlapping matches keep the best (longer on a tie), so ``"são josé dos
    campos"`` is one city, not São José plus Campos; and the words of a
    state that confirmed a match are not a city of their own, so
    ``"Campinas, São Paulo"`` is Campinas alone.

    Scores: the name similarity, times ``0.9`` when no state confirms it,
    times :data:`UNCUED_SINGLE_WORD_FACTOR` for a one-word name that does not
    look like a place (``"estou feliz"``).

    Args:
        text (str): What the user wrote.
        limit (int | None): Most matches to return; ``None`` for all.
        cutoff (float): Lowest name similarity for a typo, in ``(0, 1]``.
        min_score (float): Drop matches scoring below this.

    Returns:
        list[MunicipalityMatch]: Best first, then in text order. Homonyms
        with no state to tell them apart come back together, same score.
    """
    tokens = tokenize(text)
    index = _name_index()
    fuzzy_cache: dict[str, list[tuple[float, Municipality]]] = {}
    candidates: list[tuple[float, int, int, Municipality, int | None]] = []
    for start in range(len(tokens)):
        if tokens[start].text in LOCATIVE_CUES:
            continue
        for end in range(start + 1, min(start + MAX_NAME_TOKENS, len(tokens)) + 1):
            if tokens[end - 1].text in LOCATIVE_CUES:
                continue
            phrase = " ".join(token.text for token in tokens[start:end])
            hits = [(1.0, value) for value in index.exact(phrase)]
            if (
                not hits
                and len(phrase) >= 5
                and end - start <= 4
                and tokens[start].text not in FUZZY_EDGE_STOPWORDS
                and tokens[end - 1].text not in FUZZY_EDGE_STOPWORDS
            ):
                cached = fuzzy_cache.get(phrase)
                if cached is None:
                    cached = [
                        (hit.score, hit.value)
                        for hit in index.search(phrase, limit=None, cutoff=cutoff)
                    ]
                    fuzzy_cache[phrase] = cached
                hits = cached
            if not hits:
                continue
            state = _state_after(text, tokens, end)
            place = _looks_like_place(text, tokens, start, end)
            for similarity, municipality in hits:
                confirmed = state is not None and state[0] is municipality.uf
                if state is not None and not confirmed:
                    continue
                score = similarity * (1.0 if confirmed else 0.9)
                if not place:
                    score *= UNCUED_SINGLE_WORD_FACTOR
                state_end = state[1] if confirmed and state is not None else None
                candidates.append((score, start, end, municipality, state_end))
    candidates.sort(key=lambda item: (-item[0], -(item[2] - item[1]), item[1]))
    taken: list[tuple[int, int, float]] = []
    chosen: list[MunicipalityMatch] = []
    seen: set[int] = set()
    for score, start, end, municipality, state_end in candidates:
        if score < min_score or municipality.ibge_code in seen:
            continue
        clash = [span for span in taken if start < span[1] and span[0] < end]
        if any(
            not (span[0] == start and span[1] == end and span[2] == score)
            for span in clash
        ):
            continue
        taken.append((start, end, score))
        if state_end is not None:
            taken.append((end, state_end, -1.0))
        seen.add(municipality.ibge_code)
        confirmed = state_end is not None
        chosen.append(
            MunicipalityMatch(
                municipality=municipality,
                score=score,
                matched_text=text[tokens[start].start : tokens[end - 1].end],
                start=tokens[start].start,
                end=tokens[end - 1].end,
                uf_confirmed=confirmed,
            )
        )
    chosen.sort(key=lambda match: (-match.score, match.start))
    return chosen if limit is None else chosen[:limit]


