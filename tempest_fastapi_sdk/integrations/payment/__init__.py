"""Payment providers.

One subpackage per provider. Each one carries the provider's full API —
generated from their OpenAPI specification, checked in, and regenerated by a
script rather than edited — plus the pieces the specification leaves out:
webhook verification, the environments, and whatever the provider documents
in prose instead of in the schema.

The canonical contract lives in
:mod:`tempest_fastapi_sdk.integrations.payment.base`: a service that wants
to charge over Pix depends on ``PixProvider`` and gets ``PixCharge`` back,
whichever provider is configured. Before releasing an order on a webhook,
:func:`~tempest_fastapi_sdk.integrations.payment.settlement.confirm_pix_payment`
re-reads the charge and checks reference, status and amount. The
translations live in
:mod:`tempest_fastapi_sdk.integrations.payment.adapters`.

Available:

- **`openpix`** — OpenPix / Woovi (Pix). 358 schemas, 105 operations,
  webhook signature verification, and exact-cents helpers. Generated from
  the provider's specification.
- **`stripe`** — Stripe (cards, subscriptions, Checkout). A typed client
  with idempotent writes, webhook verification over the payload Stripe
  really signs, zero-decimal-aware money, and the 265 event types as an
  enum. Hand-written on purpose: generating Stripe's specification costs
  3.3 MB of schemas and 492 MB of RSS at import, measured — see
  ``scripts/regen_stripe.py``.

.. code-block:: python

    from tempest_fastapi_sdk import HTTPClient
    from tempest_fastapi_sdk.integrations.payment.openpix import (
        OpenPixClient,
        OpenPixEnvironment,
    )

    http: HTTPClient = HTTPClient(
        base_url=OpenPixEnvironment.SANDBOX.base_url,
        default_headers={"Authorization": "<your AppID>"},
    )
    client: OpenPixClient = OpenPixClient(http)

Importing a provider costs almost nothing: its generated schemas load on
first use, not on import. The same holds for this module — importing it
leaves ``openpix.schemas`` out of ``sys.modules``, which is what makes it
safe for the contract to live here.
"""

